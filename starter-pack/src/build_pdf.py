def nb(t):
    # неразрывный пробел после коротких слов
    import re
    t = re.sub(r'(\d) (\d{3})', r'\1' + NB + r'\2', t)
    t = re.sub(r'(\d) (₽|%|млн|минут|дн)', r'\1' + NB + r'\2', t)
    t = t.replace('₽', '<font name="DV">₽</font>')
    return re.sub(r'(?<![\w])(в|во|и|а|к|с|со|у|о|об|на|не|по|за|из|до|от|то|но|же|ли|что|для|без|при|про|как|это|его|её|их|так|уже)\s(?=\S)', lambda m: m.group(1) + NB, t, flags=re.I)

