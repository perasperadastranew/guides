def table(rows, widths, head=True):
    data = [[c if not isinstance(c, str) else P(c, 'cellb' if (head and r == 0) else 'cell') for c in row] for r, row in enumerate(rows)]
    k = (W - 2 * M) / sum(widths); widths = [w * k for w in widths]
    t = Table(data, colWidths=widths, repeatRows=1 if head else 0, hAlign='LEFT')
    st = [('VALIGN', (0, 0), (-1, -1), 'TOP'), ('LEFTPADDING', (0, 0), (-1, -1), 4), ('RIGHTPADDING', (0, 0), (-1, -1), 6),
          ('TOPPADDING', (0, 0), (-1, -1), 6), ('BOTTOMPADDING', (0, 0), (-1, -1), 7),
          ('LINEBELOW', (0, 1), (-1, -1), 0.4, LINE)]
    if head:
        st += [('BACKGROUND', (0, 0), (-1, 0), HEAD), ('LINEBELOW', (0, 0), (-1, 0), 0.8, INK)]
    t.setStyle(TableStyle(st)); return t

def box(text, style, bg):
    t = Table([[P(text, style)]], colWidths=[W - 2 * M], hAlign='LEFT')
    t.setStyle(TableStyle([('BACKGROUND', (0, 0), (-1, -1), bg), ('LEFTPADDING', (0, 0), (-1, -1), 8),
                           ('RIGHTPADDING', (0, 0), (-1, -1), 8), ('TOPPADDING', (0, 0), (-1, -1), 8), ('BOTTOMPADDING', (0, 0), (-1, -1), 10)]))
    return t

